#!/usr/bin/env python3
"""Generates crates/afirma-core/src/pades/font_metrics.rs: glyph widths of the
standard 14 PDF fonts used in visible signatures, indexed by WinAnsiEncoding code.

Input: Adobe's Core14 AFM files ("may be used, copied, and distributed for any
purpose and without charge, with or without modification"), as shipped by
matplotlib in mpl-data/fonts/pdfcorefonts. Glyph names come from matplotlib's
Unicode -> PostScript name table.

Usage: python3 -I tools/gen_font_metrics.py [AFM_DIR] > crates/afirma-core/src/pades/font_metrics.rs
"""

import sys

from matplotlib._mathtext_data import uni2type1

AFM_DIR = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/matplotlib/mpl-data/fonts/pdfcorefonts"

FONTS = [
    "Helvetica", "Helvetica-Bold", "Helvetica-Oblique", "Helvetica-BoldOblique",
    "Times-Roman", "Times-Bold", "Times-Italic", "Times-BoldItalic",
]

# Names missing from uni2type1.
EXTRA_NAMES = {
    0x20AC: "Euro", 0x2022: "bullet", 0x2026: "ellipsis", 0x2030: "perthousand",
    0x201A: "quotesinglbase", 0x0192: "florin", 0x201E: "quotedblbase", 0x02C6: "circumflex",
    0x02DC: "tilde", 0x00A4: "currency", 0x00B2: "twosuperior", 0x00B3: "threesuperior",
    0x00B9: "onesuperior", 0x00BC: "onequarter", 0x00BE: "threequarters",
}


def glyph_name(code):
    try:
        ch = bytes([code]).decode("cp1252")
    except UnicodeDecodeError:
        return None
    cp = ord(ch)
    if cp == 0x20:
        return "space"
    if cp == 0xA0:
        return "space"
    if cp == 0xAD:
        return "hyphen"
    return EXTRA_NAMES.get(cp) or uni2type1.get(cp)


def widths(font):
    by_name = {}
    with open(f"{AFM_DIR}/{font}.afm", encoding="latin-1") as afm:
        for line in afm:
            if not line.startswith("C "):
                continue
            fields = dict(
                part.strip().split(" ", 1) for part in line.split(";") if part.strip()
            )
            by_name[fields["N"]] = int(fields["WX"])
    out = []
    for code in range(32, 256):
        name = glyph_name(code)
        out.append(by_name.get(name, 0) if name else 0)
    return out


print("// Generated by tools/gen_font_metrics.py from Adobe's Core14 AFM files. Do not edit.")
print("//")
print("// Glyph widths (1/1000 em) of WinAnsiEncoding codes 32..=255; 0 means no glyph.")
print("// Courier is monospaced (600) and has no table.")
print()
for font in FONTS:
    const = font.upper().replace("-", "_")
    values = widths(font)
    print(f"pub(super) const {const}: [u16; 224] = [")
    for i in range(0, len(values), 16):
        print("    " + ", ".join(str(v) for v in values[i:i + 16]) + ",")
    print("];")
    print()
